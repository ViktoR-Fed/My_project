from datetime import datetime


def convert_date(date_string):
    """
    Принимает строку с датой в любом популярном формате
    и возвращает в формате ДД.ММ.ГГГГ
    """
    # Все возможные форматы дат для парсинга
    date_formats = [
        # ISO форматы
        "%Y-%m-%dT%H:%M:%S.%f",  # 2022-06-18T10:30:15.123456
        "%Y-%m-%dT%H:%M:%S",  # 2022-06-18T10:30:15
        "%Y-%m-%dT%H:%M:%SZ",  # 2022-06-18T10:30:15Z
        "%Y-%m-%d",  # 2022-06-18
        # Американский формат
        "%m/%d/%Y",  # 06/18/2022
        "%m/%d/%y",  # 06/18/22
        # Европейский/Российский
        "%d.%m.%Y",  # 18.06.2022
        "%d.%m.%y",  # 18.06.22
        "%d/%m/%Y",  # 18/06/2022
        "%d/%m/%y",  # 18/06/22
        # С текстовым месяцем
        "%d %B %Y",  # 18 June 2022
        "%d %b %Y",  # 18 Jun 2022
        "%B %d, %Y",  # June 18, 2022
        "%b %d, %Y",  # Jun 18, 2022
        # Обратный порядок
        "%Y/%m/%d",  # 2022/06/18
        "%Y.%m.%d",  # 2022.06.18
        # С временем
        "%d.%m.%Y %H:%M:%S",  # 18.06.2022 10:30:15
        "%d/%m/%Y %H:%M:%S",  # 18/06/2022 10:30:15
        "%Y-%m-%d %H:%M:%S",  # 2022-06-18 10:30:15
        # Компактные форматы
        "%d%m%Y",  # 18062022
        "%Y%m%d",  # 20220618
    ]

    # Очищаем строку от лишних символов в начале и конце
    clean_string = date_string.strip()

    # Пробуем каждый формат
    for date_format in date_formats:
        try:
            dt = datetime.strptime(clean_string, date_format)
            return dt.strftime("%d.%m.%Y")
        except ValueError:
            continue
